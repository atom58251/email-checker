-- =============================================================================
-- Раньше результат (xlsx) и финальный статус writes делала Edge Function
-- под service_role (обходя RLS). Теперь тяжёлая сборка результата
-- перенесена в браузер (см. web/lib/processFile.ts) из-за CPU time limit
-- Edge Functions на больших файлах (100k+ строк). Значит клиенту нужно
-- разрешить:
--   1) положить готовый xlsx в свою папку в bucket 'results'
--   2) обновить статус/статистику СВОЕЙ строки в таблице checks
--
-- Компромисс по доверию: пользователь теоретически может записать в
-- checks.stats произвольные (неверные) числа — но это ЕГО собственная
-- история в ЕГО собственном интерфейсе, не общие данные и не то, на чём
-- строится чья-то ещё защита. Источник истины (suppression_entries,
-- реальные MX-ответы) как был доступен только через Edge Function под
-- service_role, так и остался — этот компромисс их не затрагивает.
-- =============================================================================

create policy "results: пользователь загружает только в свою папку"
  on storage.objects for insert
  with check (
    bucket_id = 'results'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "checks: пользователь обновляет только свою проверку"
  on public.checks for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
