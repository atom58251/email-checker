-- =============================================================================
-- Сокращаем срок хранения результатов проверки с 14 дней до 1 дня.
--
-- Раньше: expires_at = now() + 14 дней.
-- Теперь: expires_at = now() + 1 день — минимизируем время жизни данных
-- пользовательских списков (email из чужих списков — чувствительные данные,
-- незачем им лежать в Storage/БД дольше, чем реально нужно, чтобы скачать
-- результат).
--
-- ВАЖНО: это меняет UX — пользователь должен скачать результат В ТЕЧЕНИЕ
-- СУТОК после обработки, иначе purge-expired удалит и файл, и саму строку
-- checks безвозвратно (жёсткое удаление, не "мягкое" истечение).
--
-- Существующие строки, у которых expires_at уже выставлен на 14 дней
-- вперёд, ЭТОЙ миграцией не трогаются (default применяется только к новым
-- INSERT). Если нужно, чтобы уже загруженные ранее списки тоже стали
-- короткоживущими — раскомментируйте UPDATE ниже.
-- =============================================================================

alter table public.checks
  alter column expires_at set default (now() + interval '1 day');

